# Python program to show dynamic typing

# Initially assign an integer
x = 10
print("Value of x:", x, "| Type of x:", type(x))

# Reassign a string to the same variable
x = "Hello, Python!"
print("Value of x:", x, "| Type of x:", type(x))

# Reassign a list to the same variable
x = [1, 2, 3]
print("Value of x:", x, "| Type of x:", type(x))

# Reassign a float to the same variable
x = 3.14
print("Value of x:", x, "| Type of x:", type(x))
